#!/usr/bin/env bun
// Builds src/core/generated/policy.mjs from the Bend accounting policy with the
// pinned compiler's official module emitter. `--check` verifies the committed
// artifact instead of writing it, so drift fails the gate.
//
// Inherited from pi-time-tracker; the only change is that the sources live in
// src/core and the artifact lands next to them.
import { mkdtempSync, readFileSync, rmSync, writeFileSync, mkdirSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { root, toolchain, resolveBendExecutable, resolveBendSource, assertPinnedCompiler } from "./bend-toolchain.mjs";

const generatedDir = join(root, "src", "core", "generated");
const target = join(generatedDir, "policy.mjs");
const check = process.argv.includes("--check");
// Byte-identical to the artifact inherited at 931c74c, so `--check` compares like
// for like across the two repositories.
const header = `// Generated by scripts/build-bend.mjs from engine.bend, audit.bend and batch.bend with Bend ${toolchain.version}.
// Do not edit by hand: run \`bun run build:bend\` and commit the result.
`;

async function emit() {
  const bend = assertPinnedCompiler(resolveBendExecutable());
  const source = resolveBendSource();
  const plugin = (await import(join(source, "bend2", "main.ts"))).default;
  const outdir = mkdtempSync(join(tmpdir(), "workspan-build-"));
  try {
    const built = await Bun.build({ entrypoints: [join(root, "scripts", "bend-entry.ts")], outdir, target: "node", format: "esm", plugins: [plugin], naming: "policy.mjs" });
    if (!built.success) throw new Error(built.logs.map((log) => String(log)).join("\n"));
    // Bun banners each module with a path relative to the build cwd; keep the
    // artifact byte-identical wherever the build runs.
    const code = readFileSync(join(outdir, "policy.mjs"), "utf8")
      .replace(/^\/\/ .*\/([^/\\]+\.(?:bend|ts))$/gm, "// $1");
    if (/\bbun:/.test(code)) throw new Error("generated policy still depends on Bun; it must run in plain Node");
    return header + code;
  } finally { rmSync(outdir, { recursive: true, force: true }); }
}

const produced = await emit();
if (check) {
  const current = await Bun.file(target).text().catch(() => null);
  if (current !== produced) {
    console.error("src/core/generated/policy.mjs is missing or stale. Run `bun run build:bend` and commit the result.");
    process.exit(1);
  }
  console.log("generated policy is current");
} else {
  mkdirSync(generatedDir, { recursive: true });
  writeFileSync(target, produced);
  console.log(`wrote src/core/generated/policy.mjs (${produced.length} bytes)`);
}
